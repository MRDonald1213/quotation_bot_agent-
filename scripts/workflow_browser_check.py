"""Browser QA against scripts/workflow_demo.py only; never accesses production."""
import json
import re
from pathlib import Path
from playwright.sync_api import sync_playwright

OUTPUT=Path(__file__).resolve().parents[2]/'video'/'demo-data'/'workflow-v9'/'screenshots'
OUTPUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as playwright:
    browser=playwright.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1920,'height':1080})
    errors=[]
    scan={'absolute_paths':[], 'personal_host_markers':[], 'forbidden_claims':[], 'unexpected_email_domains':[]}
    def capture(name):
        page.screenshot(path=str(OUTPUT/name))
        text=page.locator('body').inner_text()+' '+str(page.locator('input:not([type=password])').evaluate_all('(inputs)=>inputs.map(input=>input.value).join(" ")'))
        for key,pattern in [('absolute_paths',r'/Users/|/private/|/home/|[A-Z]:\\'),('personal_host_markers',r'fexreddin|celilov'),('forbidden_claims',r'time saved|money saved|\bROI\b|vector store|return on investment')]:
            if re.search(pattern,text,re.I):scan[key].append(name)
        for address in re.findall(r'[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}',text,re.I):
            if not address.endswith(('@example.test','@local.invalid')):scan['unexpected_email_domains'].append(name)
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto('http://127.0.0.1:8767')
    page.wait_for_selector('#login-form')
    page.fill('[name=username]','admin');page.fill('[name=password]','wrong');page.click('button[type=submit]')
    page.wait_for_function("document.querySelector('#login-error').textContent.includes('Incorrect')")
    capture('login.png')
    page.fill('[name=password]','1234');page.click('button[type=submit]');page.wait_for_selector('.cards')
    capture('dashboard.png')
    page.click('nav a[href="#/quotations"]');page.wait_for_function("document.querySelector('#page-title').textContent==='Quotations' && document.querySelector('#quote-rows tr') && !document.querySelector('#view .skeleton')")
    capture('quotations.png')
    page.locator('#quote-rows tr').filter(has_text='Coastal Transit').locator('a').click()
    page.wait_for_selector('#approve-quote');capture('detail.png')
    if page.locator('#clarify').count():
        page.click('#clarify');page.wait_for_selector('#quotation-draft')
        assert page.locator('#send-quotation-draft').is_disabled()
        capture('draft.png')
        page.locator('[name=body]').fill(page.locator('[name=body]').input_value()+'\nOperator note: please reply by email.')
        page.click('#save-local-draft')
        page.wait_for_function("document.querySelector('#workspace-notice').textContent.includes('saved locally')")
        page.reload();page.wait_for_selector('#quotation-draft')
        assert 'Operator note' in page.locator('[name=body]').input_value()
        capture('draft-saved.png')
        page.fill('[name=recipient]','supplier@example.test');page.click('#quotation-draft button[type=submit]')
        page.wait_for_function("document.querySelector('#workspace-notice').textContent.includes('Connect Gmail')")
        assert page.locator('#send-quotation-draft').is_disabled()
        page.click('#view > a');page.wait_for_selector('#approve-quote');page.click('[data-tab="2"]')
        page.locator('[data-answer]').last.fill('shipment, 2099-12-31')
        page.locator('[data-submit-answer]').last.click()
        page.wait_for_function("document.querySelector('#workspace-notice').textContent.includes('Response recorded')")
        capture('response.png')
        page.click('#approve-quote')
        page.wait_for_function("document.querySelector('#import-quote') && !document.querySelector('#import-quote').disabled")
        capture('approved.png')
        page.click('#import-quote')
        page.wait_for_function("document.querySelector('.workspace-toolbar').textContent.toLowerCase().includes('imported')")
    page.click('[data-tab="3"]');capture('sources.png')
    page.click('nav a[href="#/comparison"]');page.wait_for_selector('#comparison-results tbody tr')
    capture('comparison.png')
    page.fill('#comparison-query','Which supplier is fastest?');page.click('#comparison-question button')
    page.wait_for_function("document.querySelector('#comparison-explanation').textContent.includes('shortest')")
    capture('comparison-fastest.png')
    page.click('#open-assistant');page.wait_for_selector('#assistant-shipment option',state='attached')
    page.fill('#assistant-question','Which quotation is cheapest?');page.click('#assistant-form button')
    page.wait_for_function("document.querySelector('#assistant-log').textContent.includes('lowest')")
    capture('assistant.png');page.click('#close-assistant')
    page.click('nav a[href="#/archived"]');page.wait_for_function("document.querySelector('#page-title').textContent==='Archived quotations' && document.querySelector('#quote-rows tr') && !document.querySelector('#view .skeleton')");capture('archive.png')
    page.click('nav a[href="#/quotations"]');page.wait_for_function("document.querySelector('#page-title').textContent==='Quotations' && document.querySelector('#quote-rows tr') && !document.querySelector('#view .skeleton')")
    page.set_viewport_size({'width':1280,'height':900});capture('quotations-1280.png')
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.set_viewport_size({'width':1920,'height':1080})
    page.goto('http://127.0.0.1:8767/#/inbox');page.wait_for_selector('#upload-documents');capture('intake.png')
    page.goto('http://127.0.0.1:8767/#/settings');page.wait_for_function("document.querySelector('#page-title').textContent==='Settings' && document.querySelector('#view .cards')");capture('settings.png')
    page.click('a[href="#/supplier/databases"]');page.wait_for_selector('#supplier-connect-open')
    page.click('#supplier-connect-open')
    page.set_input_files('#supplier-csv-upload',{'name':'demo-suppliers.csv','mimeType':'text/csv','buffer':b'Supplier_Name,unit_price,currency,unit\nHarbor Freight,1200,USD,shipment\n'})
    page.fill('#supplier-connect-form [name=name]','Demo supplier records')
    page.click('#supplier-preview-path')
    page.wait_for_function("!document.querySelector('#supplier-submit').disabled")
    page.click('#supplier-submit');page.wait_for_selector('[data-reanalyze]')
    capture('connections.png')
    assert page.locator('#connect-gmail').count()==1
    page.click('#open-assistant');page.wait_for_selector('#assistant-shipment option[value^="database:"]',state='attached')
    database_value=page.locator('#assistant-shipment option[value^="database:"]').first.get_attribute('value')
    page.select_option('#assistant-shipment',database_value);page.fill('#assistant-question','Which supplier offers the lowest price?');page.click('#assistant-form button')
    page.wait_for_function("document.querySelector('#assistant-log').textContent.includes('recorded rate')")
    capture('assistant-database.png');page.click('#close-assistant')
    page.click('nav a[href="#/quotations"]');page.wait_for_function("document.querySelector('#page-title').textContent==='Quotations' && document.querySelector('#quote-rows tr') && !document.querySelector('#view .skeleton')")
    page.locator('#quote-rows tr').filter(has_text='Harbor Freight').locator('a').click();page.wait_for_selector('#archive-quote')
    page.click('#archive-quote');page.wait_for_selector('dialog[open]')
    page.select_option('dialog [name=disposition]','invalid');page.select_option('dialog [name=reason_code]','withdrawn');page.fill('dialog [name=reason]','Synthetic demo: supplier withdrew this quotation');page.click('dialog button[type=submit]')
    page.wait_for_function("document.querySelector('#quote-rows') && document.querySelector('#quote-rows').textContent.includes('Invalid')")
    capture('archive-decisions.png')
    text=page.locator('body').inner_text()
    assert '/Users/' not in text and '/private/' not in text
    assert not errors, errors
    assert not any(scan.values()), scan
    (OUTPUT.parent/'screen-scan.json').write_text(json.dumps(scan,indent=2))
    print(json.dumps({'browser_errors':errors,'screen_scan':scan,'viewport_checks':['1920x1080','1280x900'],'screenshots':str(OUTPUT),'flow':'login → quotation → draft → response → approve → import → comparison → assistant → archive'},indent=2))
    browser.close()
